package org.assayflux.rdms.feature.research

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.Card
import androidx.compose.material3.CardDefaults
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import org.assayflux.rdms.ai.ResearchBrief

/** One-page evidence brief. Each claim exposes its source passages to the caller. */
@Composable
fun ResearchBriefScreen(
    brief: ResearchBrief,
    onOpenSourcePassage: (claimIndex: Int, passageIndex: Int) -> Unit = { _, _ -> }
) {
    Column(
        modifier = Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        Text("Research Brief", style = MaterialTheme.typography.headlineMedium)
        Text(brief.title, style = MaterialTheme.typography.titleLarge)
        Text("Generated by ${brief.extractorId} ${brief.extractorVersion}")
        if (!brief.humanReviewed) {
            Text("AI/extraction draft — review against the original paper before citing.",
                color = MaterialTheme.colorScheme.error)
        }
        brief.objective?.let { BriefSection("Research question", listOf(it)) }
        brief.studyDesign?.let { BriefSection("Study design", listOf(it)) }
        brief.populationOrModel?.let { BriefSection("Population / model", listOf(it)) }
        brief.sampleSize?.let { BriefSection("Sample size", listOf(it)) }
        BriefSection("Methods", brief.methods)
        ClaimSection("Key findings", brief.keyFindings, onOpenSourcePassage)
        ClaimSection("Limitations", brief.limitations, onOpenSourcePassage)
        BriefSection("Key terms", brief.keyTerms)
        BriefSection("Unanswered questions", brief.unansweredQuestions)
        Text("Source-linked extraction is a reading aid, not a substitute for checking methods, results and supplementary material.",
            style = MaterialTheme.typography.bodySmall)
    }
}

@Composable
private fun BriefSection(title: String, items: List<String>) {
    if (items.isEmpty()) return
    Card(colors = CardDefaults.cardColors()) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium)
            items.forEach { Text("• $it", style = MaterialTheme.typography.bodyMedium) }
        }
    }
}

@Composable
private fun ClaimSection(
    title: String,
    claims: List<org.assayflux.rdms.ai.ExtractedResearchClaim>,
    onOpenSourcePassage: (Int, Int) -> Unit
) {
    if (claims.isEmpty()) return
    Card(colors = CardDefaults.cardColors()) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium)
            claims.forEachIndexed { claimIndex, claim ->
                Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                    Text(claim.text)
                    Text("Evidence class: ${claim.evidenceClass}; review required",
                        style = MaterialTheme.typography.labelSmall)
                    claim.supportingPassages.forEachIndexed { passageIndex, passage ->
                        androidx.compose.material3.TextButton(
                            onClick = { onOpenSourcePassage(claimIndex, passageIndex) }
                        ) {
                            Text("Open source passage ${passage.pageNumber?.let { "p. $it" } ?: ""}")
                        }
                    }
                }
            }
        }
    }
}

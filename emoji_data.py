def search_emoji(query):
    q = (query or "").strip().lower()
    if not q:
        return []
    hits = []
    for items in EMOJI.values():
        for e in items:
            if q in e.lower():
                hits.append(e)
    return hits[:80]


def all_emojis():
    out = []
    for items in EMOJI.values():
        out.extend(items)
    # de-dupe, keep order
    seen, clean = set(), []
    for e in out:
        if e not in seen:
            seen.add(e); clean.append(e)
    return clean
